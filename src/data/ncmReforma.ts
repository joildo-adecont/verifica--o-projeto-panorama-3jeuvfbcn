/** Do mais longo para o mais curto: casa sempre o mais específico primeiro. */
const CHAVES = Object.keys(CITADOS).sort((a, b) => b.length - a.length)

export function correspondenciaNcm(codigo: string): CorrespondenciaNcm {
  const k = (codigo || '').replace(/[^0-9]/g, '')
  if (!k) return { tipo: 'nenhum', anexos: [], descricao: 'Código vazio' }

  if (CITADOS[k]) {
    return {
      tipo: 'exato',
      anexos: CITADOS[k],
      descricao: 'Item citado nominalmente na legislação da reforma',
    }
  }

  for (const c of CHAVES) {
    if (c.length >= 4 && k.startsWith(c)) {
      return {
        tipo: 'posicao',
        anexos: CITADOS[c],
        descricao: 'Alcançado pela posição ' + c + ' citada na legislação',
      }
    }
  }

  for (const c of CHAVES) {
    if (k.length >= 4 && c.startsWith(k)) {
      return {
        tipo: 'posicao',
        anexos: CITADOS[c],
        descricao: 'Contém a posição ' + c + ' citada na legislação',
      }
    }
  }

  const cap = k.slice(0, 2)
  if (CAPITULOS[cap]) {
    return {
      tipo: 'capitulo',
      anexos: CAPITULOS[cap],
      descricao: 'Capítulo ' + cap + ' citado na legislação',
    }
  }

  return {
    tipo: 'nenhum',
    anexos: [],
    descricao:
      'Sem correspondência na reforma — a origem deste código é a TIPI (Res. Gecex 926/2026)',
  }
}

