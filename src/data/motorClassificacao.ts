/**
 * MOTOR DE CLASSIFICAÇÃO FISCAL DA REFORMA — gerado por scripts/auditoria/gerar_motor_classificacao.py
 *
 * NÃO EDITAR À MÃO: rode o script. A fonte é a Tabela Geral dos Anexos (Seção 7A),
 * que é a fonte única de itens do sistema, mais as tabelas do portal SVRS.
 *
 * ── POR QUE O CASAMENTO É POR PREFIXO E NÃO EXATO ──
 * O NCM do documento tem 8 dígitos; a tabela dos anexos referencia posições de
 * 4 (ex.: 0714.10.00 cobre a posição 07.14). Exigir igualdade exata faria o item
 * "não classificado" mesmo havendo regra para a sua posição — e o contador
 * concluiria que a reforma não trata daquele produto, quando trata.
 *
 * ── POR QUE O NÍVEL DE CASAMENTO APARECE NO RESULTADO ──
 * "Achei a regra do meu NCM exato" e "achei a regra da posição" são coisas
 * diferentes. A primeira é a resposta; a segunda é uma aproximação que o
 * contador tem de conferir. Esconder isso seria dar certeza onde há indício.
 */

export interface RegraNCM {
  /** NCM normalizado, só dígitos (ex.: "07141000") */
  ncm: string
  /** quantos dígitos foram usados na chave (8, 6, 4 ou 2) */
  nivel: number
  descricao: string
  tratamento: string
  aliquota: string
  anexo: string
  baseLegal: string
}

export interface ResultadoClassificacao {
  /** houve regra para o item? */
  encontrado: boolean
  /** o que foi usado para casar */
  nivel: number | null
  regra: RegraNCM | null
  /** outras regras da mesma posição, para o contador comparar */
  alternativas: RegraNCM[]
  /** texto legível do que se apurou */
  leitura: string
}

/** Normaliza NCM: tira ponto, traço e espaço; devolve só dígitos. */
export function soDigitos(v: string): string {
  return String(v || '').replace(/\D/g, '')
}

